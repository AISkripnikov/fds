    /**
     * Найти справку по ключу настройки.
     * Поддерживает точное совпадение и wildcard-паттерны (radio.*.freq).
     */
    fun forKey(key: String): FieldHelp? {
        // Точное совпадение
        fields.firstOrNull { it.key == key }?.let { return it }

        // Паттерн с wildcard
        return fields.firstOrNull { pattern ->
            val regex = pattern.key
                .replace(".", "\\.")
                .replace("*", "[^.]+")
                .toRegex()
            regex.matches(key)
        }
    }

    /**
     * Поиск по справке (поля и статьи).
     * Возвращает список Any (FieldHelp или HelpArticle).
     */
    fun search(query: String): List<Any> {
        if (query.isBlank()) return emptyList()

        val lowerQuery = query.lowercase()
        val results = mutableListOf<Any>()

        // Поиск в полях
        results.addAll(
            fields.filter {
                it.title.lowercase().contains(lowerQuery) ||
                it.description.lowercase().contains(lowerQuery) ||
                it.recommendations?.lowercase()?.contains(lowerQuery) == true
            }
        )

        // Поиск в статьях
        results.addAll(
            articles.filter {
                it.title.lowercase().contains(lowerQuery) ||
                it.body.lowercase().contains(lowerQuery) ||
                it.tags.any { tag -> tag.lowercase().contains(lowerQuery) }
            }
        )

        return results
    }
