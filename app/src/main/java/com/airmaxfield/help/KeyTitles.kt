    private val compiled: List<Pair<Regex, String>> = titles.map { (pattern, title) ->
        Regex("^" + pattern.split("*").joinToString("[^.]+") { Regex.escape(it) } + "$") to title
    }

    fun forKey(key: String): String? = compiled.firstOrNull { it.first.matches(key) }?.second

    /** Название поля: подробная справка → словарь → сам ключ. */
    fun titleFor(key: String): String = HelpContent.forKey(key)?.title ?: forKey(key) ?: key
